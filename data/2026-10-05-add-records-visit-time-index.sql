-- 批次 12：病历列表排序索引（性能基线与复测数据见下方注释）
--
-- 问题：病历列表统一 `ORDER BY visit_time DESC, id ASC`（RecordFilter:99/317），
-- 而既有索引是 `(department, visit_time)` —— 前导列不匹配 ⇒ 全局排序走 filesort。
--
-- 实测（35,500 条，MySQL 服务端 NOW(6) 计时）：
--   ┌────────────────────────┬──────────┬──────────┐
--   │ 场景                    │ 无本索引 │ 有本索引 │
--   ├────────────────────────┼──────────┼──────────┤
--   │ 分页 offset 500（第25页）│ 235 ms   │  25 ms   │
--   │ 分页 offset 30000       │ 195 ms   │  48 ms   │
--   │ 按月聚合（12 组）        │ 249 ms   │  14.6 ms │
--   └────────────────────────┴──────────┴──────────┘
--
-- 一段值得留下的过程（避免后人重走）：
--   第一次复测深分页得到 1034 ms（比基线慢 5 倍），一度得出「索引拖慢深分页」的结论。
--   随后补齐三档深度 + 去掉索引做对照，才发现那次是**瞬时抖动**：索引在三档深度上都快于无索引。
--   ⇒ 性能结论必须来自「多档取值 + 对照组」，单次读数不足以下结论。
--
-- 为什么只建 (visit_time) 而不建 (visit_time, id)：
--   InnoDB 二级索引自动包含主键，排序的第二列是主键 id，因此 (visit_time) 已能覆盖
--   `ORDER BY visit_time DESC, id ASC`，再带上 id 只是重复存储。
--
-- 回滚：DROP INDEX idx_records_visit_time ON records;

CREATE INDEX idx_records_visit_time ON records (visit_time);
