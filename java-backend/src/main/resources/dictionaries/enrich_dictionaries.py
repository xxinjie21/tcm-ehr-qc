def clean_alias(a):
    if not isinstance(a, str):
        return None
    a = a.strip()
    if not a:
        return None
    # 清理说明性脏数据（带句号的描述、纯数字等）
    if a.endswith("。") or a.endswith("."):
        return None
    if len(a) < 1:
        return None
    # 清理含"病。"等说明性后缀的条目
    if re.search(r"病[。.]?$", a) and len(a) > 6 and ("之" in a or "。" in a):
        return None
    return a

def enrich(name):
    src = os.path.join(BASE, f"{name} - 副本.json")
    if not os.path.exists(src):
        print(f"[SKIP] {src} not found")
        return
    with open(src, encoding="utf-8") as f:
        data = json.load(f, object_pairs_hook=OrderedDict)

    amap = ALIAS_MAPS.get(name, {})
    new_entries = NEW_ENTRIES.get(name, [])
    stats = {"total": len(data), "enriched": 0, "new_aliases": 0, "cleaned": 0, "added": 0}

    # 建立现有 standardTerm 索引，避免重复
    existing_terms = OrderedDict()
    for item in data:
        st = item.get("standardTerm")
        if st:
            existing_terms[st] = item

    for item in data:
        st = item.get("standardTerm")
        if not st:
            continue
        existing = item.get("aliases") or []
        cleaned = []
        seen = set()
        for a in existing:
            c = clean_alias(a)
            if c and c != st and c not in seen:
                seen.add(c)
                cleaned.append(c)
        if len(cleaned) != len(existing):
            stats["cleaned"] += len(existing) - len(cleaned)
        new_aliases = amap.get(st, [])
        for a in new_aliases:
            c = clean_alias(a)
            if c and c != st and c not in seen:
                seen.add(c)
                cleaned.append(c)
        if len(cleaned) > len(existing):
            stats["enriched"] += 1
            stats["new_aliases"] += len(cleaned) - len(existing)
        item["aliases"] = cleaned

    # 追加新条目（不重复的才加）
    for ne in new_entries:
        st = ne.get("standardTerm")
        if not st:
            continue
        if st in existing_terms:
            # 已存在：合并别名
            target = existing_terms[st]
            existing = target.get("aliases") or []
            seen = set(existing)
            for a in ne.get("aliases", []):
                c = clean_alias(a)
                if c and c != st and c not in seen:
                    seen.add(c)
                    existing.append(c)
            target["aliases"] = existing
        else:
            # 追加新条目
            cleaned_aliases = []
            seen = set()
            for a in ne.get("aliases", []):
                c = clean_alias(a)
                if c and c != st and c not in seen:
                    seen.add(c)
                    cleaned_aliases.append(c)
            data.append(OrderedDict([("standardTerm", st), ("aliases", cleaned_aliases)]))
            existing_terms[st] = data[-1]
            stats["added"] += 1

    out = os.path.join(BASE, f"{name}.enriched.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    empty_after = sum(1 for x in data if not x.get("aliases"))
    print(f"[{name}] total={len(data)} (原{stats['total']}, 新增{stats['added']}) "
          f"enriched_entries={stats['enriched']} new_aliases={stats['new_aliases']} "
          f"cleaned={stats['cleaned']} empty_aliases={empty_after}")

if __name__ == "__main__":
    for n in ["diseases", "patterns", "pulses", "symptoms", "tongues", "treatments", "formulas", "herbs"]:
        enrich(n)
    print("Done. Output: *.enriched.json")
